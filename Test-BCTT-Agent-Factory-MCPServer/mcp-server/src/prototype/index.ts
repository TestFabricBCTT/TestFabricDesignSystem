/**
 * Creates a new prototype from wireframes
 */
export function generatePrototype(input: PrototypeInput): PrototypeRecord {
  const screens: GeneratedScreen[] = input.wireframes.map(wireframe => {
    const translations = extractTranslations(wireframe);
    const code = generateScreenCode(wireframe);
    const components: ScreenComponent[] = wireframe.body.sections.flatMap(s =>
      s.components.map(c => ({
        type: c.type,
        props: c.props || {},
        i18nKey: c.i18nKey,
        children: c.children as ScreenComponent[] | undefined,
      }))
    );

    return {
      screenId: wireframe.screenId,
      screenName: wireframe.screenName,
      userStory: wireframe.userStory,
      components,
      code,
      translations,
    };
  });

  // Check if prototype exists
  if (prototypeExists(input.bdevCode)) {
    const existingPrototype = loadPrototype(input.bdevCode);
    if (existingPrototype) {
      // Create new version with changes
      return updatePrototype(
        input.bdevCode,
        screens,
        input.journeys,
        input.approvedBy || 'PA',
        `Updated prototype based on ${input.approvedBy || 'PA'} input`
      );
    }
  }

  // Create new prototype
  return createPrototype(input.bdevCode, input.journeys, screens, input.approvedBy);
}

/**
 * Gets or creates a prototype for a BDEV
 */
export function getOrCreatePrototype(input: PrototypeInput): PrototypeRecord {
  const existing = loadPrototype(input.bdevCode);

  if (existing) {
    return existing;
  }

  return generatePrototype(input);
}

/**
 * Compares FA approved version with Client approved version
 */
export function compareFAvsClient(bdevCode: string): PrototypeComparison | null {
  const prototypes = listPrototypes(bdevCode);

  const faApproved = prototypes.find(p => p.status === 'fa_approved');
  const clientApproved = prototypes.find(p => p.status === 'client_approved');

  if (!faApproved || !clientApproved) {
    return null;
  }

  const faPrototype = loadPrototype(bdevCode, faApproved.version);
  const clientPrototype = loadPrototype(bdevCode, clientApproved.version);

  if (!faPrototype || !clientPrototype) {
    return null;
  }

  return comparePrototypes(faPrototype, clientPrototype);
}

/**
 * Applies client changes to create final version
 */
export function applyClientChanges(bdevCode: string): PrototypeRecord | null {
  const comparison = compareFAvsClient(bdevCode);

  if (!comparison) {
    return null;
  }

  const clientPrototype = loadPrototype(bdevCode);
  if (!clientPrototype || clientPrototype.status !== 'client_approved') {
    return null;
  }

  // Create final version based on client approved
  const finalPrototype = updatePrototype(
    bdevCode,
    clientPrototype.screens,
    clientPrototype.journeySnapshot,
    'PA',
    `Final version created based on client approved changes`
  );

  // Generate App router code
  finalPrototype.appCode = generateAppRouter(finalPrototype.screens, bdevCode);

  // Merge all translations
  const allTranslations = { pt: {} as Record<string, string>, en: {} as Record<string, string> };
  for (const screen of finalPrototype.screens) {
    Object.assign(allTranslations.pt, screen.translations.pt);
    Object.assign(allTranslations.en, screen.translations.en);
  }
  finalPrototype.translationsJson = allTranslations;

  return finalPrototype;
}

/**
 * Exports prototype as a structured package
 */
export function exportPrototype(bdevCode: string, version?: number): {
  screens: Array<{ filename: string; code: string }>;
  app: { filename: string; code: string };
  translations: {
    pt: { filename: string; content: string };
    en: { filename: string; content: string };
  };
  readme: string;
} | null {
  const prototype = loadPrototype(bdevCode, version);
  if (!prototype) return null;

  const screens = prototype.screens.map(s => ({
    filename: `${s.screenName.replace(/[^a-zA-Z0-9]/g, '')}.tsx`,
    code: s.code,
  }));

  const appCode = prototype.appCode || generateAppRouter(prototype.screens, bdevCode);

  const allPt: Record<string, string> = {};
  const allEn: Record<string, string> = {};
  for (const screen of prototype.screens) {
    Object.assign(allPt, screen.translations.pt);
    Object.assign(allEn, screen.translations.en);
  }

  const readme = `# ${bdevCode} - Prototype

## Generated by PA (Prototype Agent)

### Version: ${prototype.version}
### Status: ${prototype.status}

## Screens
${prototype.screens.map(s => `- ${s.screenName} (${s.screenId})`).join('\n')}

## Setup
1. Copy files to your React project
2. Install dependencies: \`npm install @bctt/design-system react-router-dom react-i18next i18next\`
3. Import the App component

## Notes
- This is a non-functional prototype using BCTT Design System
- All actions are placeholders
- Translations are included in PT and EN
- Uses bctt-design-system components (Button, Input, Card, etc.)
`;

  return {
    screens,
    app: { filename: 'App.tsx', code: appCode },
    translations: {
      pt: { filename: 'pt.json', content: JSON.stringify(allPt, null, 2) },
      en: { filename: 'en.json', content: JSON.stringify(allEn, null, 2) },
    },
    readme,
  };
}
