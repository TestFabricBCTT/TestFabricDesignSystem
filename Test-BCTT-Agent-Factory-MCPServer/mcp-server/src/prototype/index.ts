/**
 * Generates React component code for a screen
 */
function generateScreenCode(screen: WireframeScreen): string {
  const componentName = screen.screenName
    .replace(/[^a-zA-Z0-9]/g, '')
    .replace(/^./, c => c.toUpperCase());

  const imports = new Set<string>(['Box', 'Typography']);
  const bodyComponents: string[] = [];

  // Process body sections
  for (const section of screen.body.sections) {
    for (const component of section.components) {
      const { code, importList } = generateComponentCode(component, screen.screenId);
      bodyComponents.push(code);
      importList.forEach(i => imports.add(i));
    }
  }

  // Generate footer actions
  let footerCode = '';
  if (screen.footer?.primaryAction || screen.footer?.secondaryAction) {
    imports.add('Button');
    const buttons: string[] = [];
    if (screen.footer.secondaryAction) {
      buttons.push(`        <Button variant="outlined" fullWidth>
          {t('${screen.screenId}.footer.secondary')}
        </Button>`);
    }
    if (screen.footer.primaryAction) {
      buttons.push(`        <Button variant="contained" color="primary" fullWidth>
          {t('${screen.screenId}.footer.primary')}
        </Button>`);
    }
    footerCode = `
      {/* Footer Actions */}
      <Box sx={{
        position: 'fixed',
        bottom: 0,
        left: 0,
        right: 0,
        p: 2,
        bgcolor: 'background.paper',
        borderTop: 1,
        borderColor: 'divider',
        display: 'flex',
        flexDirection: 'column',
        gap: 1,
      }}>
${buttons.join('\n')}
      </Box>`;
  }

  // Generate header
  let headerCode = '';
  if (screen.header) {
    imports.add('AppBar');
    imports.add('Toolbar');
    imports.add('IconButton');
    const backButton = screen.header.backButton
      ? `<IconButton edge="start" onClick={() => navigate(-1)}>
            <ArrowBackIcon />
          </IconButton>`
      : '';
    const closeButton = screen.header.closeButton
      ? `<IconButton edge="end" onClick={() => navigate('/')}>
            <CloseIcon />
          </IconButton>`
      : '';
    headerCode = `
      <AppBar position="fixed" color="default" elevation={0}>
        <Toolbar>
          ${backButton}
          <Typography variant="h6" sx={{ flexGrow: 1 }}>
            {t('${screen.screenId}.header.title')}
          </Typography>
          ${closeButton}
        </Toolbar>
      </AppBar>
      <Toolbar /> {/* Spacer for fixed header */}`;
  }

  const code = `/**
 * ${screen.screenName}
 * Screen ID: ${screen.screenId}
 * ${screen.userStory ? `User Story: ${screen.userStory}` : ''}
 *
 * PROTOTYPE - Non-functional component
 * Generated by PA (Prototype Agent)
 */

import React from 'react';
import { useTranslation } from 'react-i18next';
import { useNavigate } from 'react-router-dom';
import {
  ${Array.from(imports).join(',\n  ')},
} from '@bctt/design-system';
import { ArrowBack as ArrowBackIcon, Close as CloseIcon } from '@bctt/design-system/icons';

export interface ${componentName}Props {
  // Props can be added as needed
}

export const ${componentName}: React.FC<${componentName}Props> = () => {
  const { t } = useTranslation();
  const navigate = useNavigate();

  return (
    <Box sx={{ minHeight: '100vh', bgcolor: 'greyblue.100', pb: 10 }}>
      ${headerCode}

      {/* Body Content */}
      <Box sx={{ p: 2, maxWidth: 600, mx: 'auto' }}>
${bodyComponents.map(c => '        ' + c).join('\n\n')}
      </Box>
      ${footerCode}
    </Box>
  );
};

export default ${componentName};
`;

  return code;
}

/**
 * Generates code for a single component
 */
function generateComponentCode(
  element: WireframeElement,
  screenId: string,
  indent: number = 0
): { code: string; importList: string[] } {
  const imports: string[] = [];
  let code = '';
  const i18nKey = element.i18nKey || `${screenId}.${element.type}.${element.name}`;

  switch (element.type.toLowerCase()) {
    case 'button':
      imports.push('Button');
      code = `<Button
  variant="${element.props?.variant || 'contained'}"
  color="${element.props?.color || 'primary'}"
  fullWidth
>
  {t('${i18nKey}')}
</Button>`;
      break;

    case 'textfield':
    case 'input':
      imports.push('TextField');
      code = `<TextField
  label={t('${i18nKey}.label')}
  placeholder={t('${i18nKey}.placeholder')}
  fullWidth
  ${element.props?.required ? 'required' : ''}
  ${element.props?.type ? `type="${element.props.type}"` : ''}
  helperText={t('${i18nKey}.helper')}
/>`;
      break;

    case 'card':
      imports.push('Card', 'CardContent');
      const cardChildren = element.children
        ? element.children.map(c => {
            const result = generateComponentCode(c, screenId, indent + 2);
            result.importList.forEach(i => imports.push(i));
            return result.code;
          }).join('\n')
        : `<Typography>{t('${i18nKey}')}</Typography>`;
      code = `<Card sx={{ mb: 2 }}>
  <CardContent>
    ${cardChildren}
  </CardContent>
</Card>`;
      break;

    case 'title':
    case 'heading':
      imports.push('Typography');
      code = `<Typography variant="${element.props?.variant || 'h5'}" gutterBottom>
  {t('${i18nKey}')}
</Typography>`;
      break;

    case 'text':
    case 'description':
    case 'paragraph':
      imports.push('Typography');
      code = `<Typography variant="body1" color="text.secondary" sx={{ mb: 2 }}>
  {t('${i18nKey}')}
</Typography>`;
      break;

    case 'alert':
      imports.push('Alert');
      code = `<Alert severity="${element.props?.severity || 'info'}" sx={{ mb: 2 }}>
  {t('${i18nKey}')}
</Alert>`;
      break;

    case 'divider':
      imports.push('Divider');
      code = `<Divider sx={{ my: 2 }} />`;
      break;

    case 'select':
      imports.push('FormControl', 'InputLabel', 'Select', 'MenuItem');
      code = `<FormControl fullWidth sx={{ mb: 2 }}>
  <InputLabel>{t('${i18nKey}.label')}</InputLabel>
  <Select label={t('${i18nKey}.label')}>
    <MenuItem value="">{t('common.select')}</MenuItem>
  </Select>
</FormControl>`;
      break;

    case 'checkbox':
      imports.push('FormControlLabel', 'Checkbox');
      code = `<FormControlLabel
  control={<Checkbox />}
  label={t('${i18nKey}')}
/>`;
      break;

    case 'radio':
      imports.push('FormControl', 'FormLabel', 'RadioGroup', 'FormControlLabel', 'Radio');
      code = `<FormControl component="fieldset" sx={{ mb: 2 }}>
  <FormLabel>{t('${i18nKey}.label')}</FormLabel>
  <RadioGroup>
    <FormControlLabel value="option1" control={<Radio />} label={t('${i18nKey}.option1')} />
    <FormControlLabel value="option2" control={<Radio />} label={t('${i18nKey}.option2')} />
  </RadioGroup>
</FormControl>`;
      break;

    case 'list':
      imports.push('List', 'ListItem', 'ListItemText');
      code = `<List>
  <ListItem>
    <ListItemText primary={t('${i18nKey}.item1')} />
  </ListItem>
</List>`;
      break;

    default:
      imports.push('Box');
      code = `<Box sx={{ mb: 2 }}>
  {/* ${element.type}: ${element.name} */}
  <Typography>{t('${i18nKey}')}</Typography>
</Box>`;
  }

  return { code, importList: imports };
}

/**
 * Generates App.tsx with routes for all screens
 */
function generateAppRouter(screens: GeneratedScreen[], bdevCode: string): string {
  const imports = screens.map(s => {
    const componentName = s.screenName.replace(/[^a-zA-Z0-9]/g, '').replace(/^./, c => c.toUpperCase());
    return `import { ${componentName} } from './screens/${componentName}';`;
  }).join('\n');

  const routes = screens.map(s => {
    const componentName = s.screenName.replace(/[^a-zA-Z0-9]/g, '').replace(/^./, c => c.toUpperCase());
    const path = s.screenId.toLowerCase().replace(/[^a-z0-9]/g, '-');
    return `        <Route path="/${path}" element={<${componentName} />} />`;
  }).join('\n');

  return `/**
 * App Router
 * BDEV: ${bdevCode}
 *
 * PROTOTYPE - Non-functional application
 * Generated by PA (Prototype Agent)
 */

import React from 'react';
import { BrowserRouter, Routes, Route, Navigate } from 'react-router-dom';
import { ThemeProvider } from '@mui/material/styles';
import CssBaseline from '@mui/material/CssBaseline';
import { bcttTheme } from '@bctt/design-system';
import './i18n'; // i18n configuration

${imports}

const App: React.FC = () => {
  return (
    <ThemeProvider theme={bcttTheme}>
      <CssBaseline />
      <BrowserRouter>
        <Routes>
${routes}
          <Route path="*" element={<Navigate to="/${screens[0]?.screenId.toLowerCase().replace(/[^a-z0-9]/g, '-') || ''}" replace />} />
        </Routes>
      </BrowserRouter>
    </ThemeProvider>
  );
};

export default App;
`;
}

/**
 * Extracts translations from wireframe
 */
function extractTranslations(wireframe: WireframeScreen): { pt: Record<string, string>; en: Record<string, string> } {
  const pt: Record<string, string> = {};
  const en: Record<string, string> = {};

  // Header translations
  if (wireframe.header) {
    pt[`${wireframe.screenId}.header.title`] = wireframe.header.titlePT || wireframe.header.title;
    en[`${wireframe.screenId}.header.title`] = wireframe.header.titleEN || wireframe.header.title;
  }

  // Footer translations
  if (wireframe.footer) {
    if (wireframe.footer.primaryAction) {
      pt[`${wireframe.screenId}.footer.primary`] = wireframe.footer.primaryActionPT || wireframe.footer.primaryAction;
      en[`${wireframe.screenId}.footer.primary`] = wireframe.footer.primaryActionEN || wireframe.footer.primaryAction;
    }
    if (wireframe.footer.secondaryAction) {
      pt[`${wireframe.screenId}.footer.secondary`] = wireframe.footer.secondaryActionPT || wireframe.footer.secondaryAction;
      en[`${wireframe.screenId}.footer.secondary`] = wireframe.footer.secondaryActionEN || wireframe.footer.secondaryAction;
    }
  }

  // Body component translations
  function processElements(elements: WireframeElement[], prefix: string) {
    for (const element of elements) {
      const key = element.i18nKey || `${prefix}.${element.type}.${element.name}`;
      if (element.valuePT) pt[key] = element.valuePT;
      if (element.valueEN) en[key] = element.valueEN;

      // Process children recursively
      if (element.children) {
        processElements(element.children, key);
      }
    }
  }

  for (const section of wireframe.body.sections) {
    processElements(section.components, wireframe.screenId);
  }

  return { pt, en };
}

