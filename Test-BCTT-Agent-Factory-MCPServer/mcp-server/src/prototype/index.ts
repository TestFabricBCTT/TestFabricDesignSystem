export interface WireframeElement {
  type: string;
  name: string;
  props?: Record<string, unknown>;
  children?: WireframeElement[];
  i18nKey?: string;
  valuePT?: string;
  valueEN?: string;
}

export interface WireframeScreen {
  screenId: string;
  screenName: string;
  userStory?: string;
  header?: {
    title: string;
    titlePT?: string;
    titleEN?: string;
    backButton?: boolean;
    closeButton?: boolean;
  };
  body: {
    sections: Array<{
      type: string;
      components: WireframeElement[];
    }>;
  };
  footer?: {
    primaryAction?: string;
    primaryActionPT?: string;
    primaryActionEN?: string;
    secondaryAction?: string;
    secondaryActionPT?: string;
    secondaryActionEN?: string;
  };
}

export interface PrototypeInput {
  bdevCode: string;
  journeys: Journey[];
  wireframes: WireframeScreen[];
  approvedBy?: 'FA' | 'Client';
}

